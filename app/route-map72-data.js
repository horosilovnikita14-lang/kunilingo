export const examTasks = tasks.map(([title, skill], index) => {
  const number = index + 1;
  return {number, title, skill, stageId: routeStages.find(stage => stage.tasks.includes(number)).id};
});

export function routeTo(targets) {
  const needed = new Set();
  function include(id) {
    const stage = routeStages.find(item => item.id === id);
    if (!stage || needed.has(id)) return;
    needed.add(id);
    stage.prerequisites.forEach(include);
  }
  targets.forEach(include);
  return [...routeStages.filter(stage => needed.has(stage.id)), ...routeStages.filter(stage => !needed.has(stage.id))];
}
